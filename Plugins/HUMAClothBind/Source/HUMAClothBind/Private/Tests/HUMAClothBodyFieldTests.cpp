TArray<FVector> Vectors(const TSharedPtr<FJsonObject>& Object, const TCHAR* Name)
{
    TArray<FVector> Result;
    for (const auto& Value : Object->GetArrayField(Name))
    {
        const auto& Row = Value->AsArray();
        Result.Emplace(Row[0]->AsNumber(), Row[1]->AsNumber(), Row[2]->AsNumber());
    }
    return Result;
}

void WriteVectors(const TSharedPtr<FJsonObject>& Object, const TCHAR* Name, const TArray<FVector>& Values)
{
    TArray<TSharedPtr<FJsonValue>> Result;
    for (const FVector& Value : Values)
    {
        TArray<TSharedPtr<FJsonValue>> Row;
        for (int32 Axis = 0; Axis < 3; ++Axis) Row.Add(MakeShared<FJsonValueNumber>(Value[Axis]));
        Result.Add(MakeShared<FJsonValueArray>(Row));
    }
    Object->SetArrayField(Name, Result);
}

template<typename T>
void WriteNumbers(const TSharedPtr<FJsonObject>& Object, const TCHAR* Name, const TArray<T>& Values)
{
    TArray<TSharedPtr<FJsonValue>> Result;
    for (const T Value : Values) Result.Add(MakeShared<FJsonValueNumber>(double(Value)));
    Object->SetArrayField(Name, Result);
}

TSharedPtr<FJsonObject> Table(const UHUMAClothBindAsset& Asset)
{
    auto Result = MakeShared<FJsonObject>();
    Result->SetStringField(TEXT("bind_method"), Asset.BindMethod);
    TArray<FVector> Triangles;
    for (const FIntVector& Triangle : Asset.AnchorTriangles) Triangles.Emplace(Triangle.X, Triangle.Y, Triangle.Z);
    WriteVectors(Result, TEXT("anchor_triangles"), Triangles);
    WriteVectors(Result, TEXT("anchor_barycentrics"), Asset.AnchorBarycentrics);
    WriteVectors(Result, TEXT("anchor_rest_positions"), Asset.AnchorRestPositions);
    WriteVectors(Result, TEXT("anchor_rest_tangents"), Asset.AnchorRestTangents);
    WriteVectors(Result, TEXT("anchor_rest_bitangents"), Asset.AnchorRestBitangents);
    WriteVectors(Result, TEXT("anchor_rest_normals"), Asset.AnchorRestNormals);
    WriteNumbers(Result, TEXT("influence_anchors"), Asset.InfluenceAnchors);
    WriteNumbers(Result, TEXT("influence_weights"), Asset.InfluenceWeights);
    return Result;
}
